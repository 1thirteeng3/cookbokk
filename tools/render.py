def _front(title: str) -> str:
    return f'---\ntitle: "{title}"\n---\n\n'


def _status(lang: str, s: str, kind: str = "recipe") -> str:
    if kind == "project" and lang == "pt":
        return PROJECT_STATUS_PT[s]
    return STATUS_LABEL[lang][s]


def _replace_block(text: str, name: str, content: str) -> str:
    pat = re.compile(rf"(<!-- {name}:START -->\n).*?(<!-- {name}:END -->)", re.S)
    if not pat.search(text):
        return text
    return pat.sub(lambda m: m.group(1) + content.rstrip("\n") + "\n" + m.group(2), text)


