def nav(cat: Catalog, lang: str) -> list:
    t = L[lang]
    recipes_nav = []
    for g in cat.parts.values():
        entries: list = [f"recipes/{g.path.name}/index.md"]
        for code, st in g.meta["sections"].items():
            sec_items = [i.rel(DOCS) for i in g.items if i.meta["section"] == code]
            entries.append(
                {f"{code} · {st[lang]}": [f"recipes/{g.path.name}/{code}/index.md", *sec_items]}
            )
        recipes_nav.append({f"{g.code} · {g.meta['title'][lang]}": entries})
    projects_nav: list = ["projects/index.md"]
    for g in cat.groups.values():
        projects_nav.append(
            {
                f"{g.code} · {g.meta['title'][lang]}": [f"projects/{g.path.name}/index.md"]
                + [i.rel(DOCS) for i in g.items]
            }
        )
    return [
        {t["home"]: "index.md"},
        {t["recipes"]: recipes_nav},
        {t["projects"]: projects_nav},
        {t["glossary"]: "glossary.md"},
    ]


