def build(cat: Catalog) -> dict[Path, str]:
    out: dict[Path, str] = {}
    for g in cat.parts.values():
        for lang in LANGS:
            out[g.path / f"index.{lang}.md"] = part_page(g, lang)
            for code in g.meta["sections"]:
                out[g.path / code / f"index.{lang}.md"] = section_page(g, code, lang)
    for g in cat.groups.values():
        for lang in LANGS:
            out[g.path / f"index.{lang}.md"] = group_page(g, lang)
    for lang in LANGS:
        out[PROJECTS / f"index.{lang}.md"] = projects_page(cat, lang)
        home = DOCS / f"index.{lang}.md"
        if home.exists():
            out[home] = _replace_block(
                home.read_text(encoding="utf-8"), "PROGRESS", progress_block(cat, lang)
            )
    for item in cat.all_items():
        for lang in LANGS:
            doc = item.doc(lang)
            if not doc.exists():
                continue
            text = doc.read_text(encoding="utf-8")
            new = _replace_block(text, "SUMMARY", summary_block(item, lang))
            if item.kind == "recipe":
                new = _replace_block(new, "BENCHMARK", benchmark_block(item, lang))
            else:
                for tier in ("L1", "L3", "L4"):
                    new = _replace_block(
                        new, f"RESULTS-{tier}", tier_results_block(item, tier, lang)
                    )
            if new != text:
                out[doc] = new
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()
    outputs = build(load_catalog())
    stale = [
        p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text
    ]
    if args.check:
        for p in stale:
            print("STALE", p.relative_to(ROOT))
        print(f"{len(stale)} stale file(s)" + (" — run `make render`" if stale else ""))
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outputs[p], encoding="utf-8")
    print(f"render: {len(stale)} file(s) written, {len(outputs) - len(stale)} up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
