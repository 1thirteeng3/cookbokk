def summary_block(item: Item, lang: str) -> str:
    t, m = L[lang], item.meta
    verified = m.get("last_verified") or "—"
    runtime = m["environment"]["colab_runtime"]
    if item.kind == "recipe":
        return (
            f"| {t['entry']} | {t['stacks']} | {t['runtime']} | {t['status']} | {t['verified']} |\n"
            "|---|---|---|---|---|\n"
            f"| {LEVEL_LABEL[lang][m['level']]} | {len(m.get('stacks', []))} | {runtime} | "
            f"{_status(lang, m['status'], item.kind)} | {verified} |\n"
        )
    return (
        f"| {t['domain']} | {t['refs']} | {t['tiers']} | {t['runtime']} | {t['status']} | {t['verified']} |\n"
        "|---|---|---|---|---|---|\n"
        f"| {m['domain']} | {len(m.get('recipes', []))} | L1 · L3 · L4 | {runtime} | "
        f"{_status(lang, m['status'], item.kind)} | {verified} |\n"
    )


def _fmt(metric: dict | None) -> str:
    if not metric:
        return "—"
    s = f"{metric['mean']:.4g}"
    if metric.get("std") is not None:
        s += f" ± {metric['std']:.2g}"
    return s


def benchmark_block(item: Item, lang: str) -> str:
    t, m = L[lang], item.meta
    files = sorted(item.path.glob("results/*.full.json"))
    if not files:
        return t["no_results"] + "\n"
    results = [json.loads(f.read_text(encoding="utf-8")) for f in files]
    order = {Path(s["notebook"]).stem: n for n, s in enumerate(m.get("stacks", []))}
    results.sort(key=lambda r: (order.get(r["notebook"], 99), r["notebook"], r.get("variant", "")))
    primary = m.get("metrics", {}).get("primary")
    secondary = [
        s
        for s in m.get("metrics", {}).get("secondary", [])
        if any(s in r["metrics"] for r in results)
    ]
    cols = [primary, *secondary]
    head = (
        f"| {t['stack']} | "
        + " | ".join(f"**{primary}**" if c == primary else c for c in cols)
        + f" | {t['train']} | {t['infer']} | {t['mem']} | {t['hw']} |"
    )
    lines = [head, "|" + "---|" * (len(cols) + 5)]
    for r in results:
        label = r["stack"] + (f" ({r['variant']})" if r.get("variant") else "")
        hw = r["hardware"].get("gpu") or r["hardware"]["cpu"]
        inf = r["time_s"].get("inference_per_1k")
        lines.append(
            f"| {label} | "
            + " | ".join(_fmt(r["metrics"].get(c)) for c in cols)
            + f" | {r['time_s']['train']:.3g} | {'—' if inf is None else f'{inf:.3g}'} | "
            f"{r.get('peak_mem_mb') or '—'} | {hw} |"
        )
    datasets = sorted({r["dataset"]["name"] for r in results})
    dates = sorted({r["timestamp"][:10] for r in results})
    lines.append(
        f"\n**{t['conditions']}:** {t['dataset']} {', '.join(datasets)} · "
        f"{t['runs']} {dates[0]}" + (f" → {dates[-1]}" if len(dates) > 1 else "")
    )
    return "\n".join(lines) + "\n"


def tier_results_block(item: Item, tier: str, lang: str) -> str:
    """Results of one project tier (L1/L3/L4): one small table per notebook.

    Each table only shows the metrics that notebook produced, ordered by the project's
    ``technical_metrics``, so tiers with heterogeneous notebooks stay readable.
    """
    t, m = L[lang], item.meta
    stems = [Path(nb).stem for nb in m.get("tiers", {}).get(tier, {}).get("notebooks", [])]
    results = []
    for f in sorted(item.path.glob("results/*.full.json")):
        r = json.loads(f.read_text(encoding="utf-8"))
        if r["notebook"] in stems:
            results.append(r)
    if not results:
        return t["no_results"] + "\n"
    order = {c: n for n, c in enumerate(m.get("technical_metrics", []))}
    lines: list[str] = []
    for stem in stems:
        rows = sorted(
            (r for r in results if r["notebook"] == stem), key=lambda r: r.get("variant", "")
        )
        if not rows:
            continue
        cols = sorted({k for r in rows for k in r["metrics"]}, key=lambda c: (order.get(c, 99), c))
        lines += [
            f"\n**`{stem}`**\n",
            f"| {t['stack']} | " + " | ".join(cols) + f" | {t['train']} |",
            "|" + "---|" * (len(cols) + 2),
        ]
        for r in rows:
            label = r["stack"] + (f" · {r['variant']}" if r.get("variant") else "")
            lines.append(
                f"| {label} | "
                + " | ".join(_fmt(r["metrics"].get(c)) for c in cols)
                + f" | {r['time_s']['train']:.3g} |"
            )
    datasets = sorted({r["dataset"]["name"] for r in results})
    dates = sorted({r["timestamp"][:10] for r in results})
    hardware = sorted({r["hardware"].get("gpu") or r["hardware"]["cpu"] for r in results})
    lines.append(
        f"\n**{t['conditions']}:** {t['dataset']} {', '.join(datasets)} · {', '.join(hardware)} · "
        f"{t['runs']} {dates[0]}" + (f" → {dates[-1]}" if len(dates) > 1 else "")
    )
    return "\n".join(lines).lstrip("\n") + "\n"


