def part_page(g: Group, lang: str) -> str:
    t = L[lang]
    title = f"{g.code} · {g.meta['title'][lang]}"
    secs = g.meta["sections"]
    out = [
        _front(title),
        GENERATED,
        f"# {title}\n",
        t["part_intro"].format(n=len(g.items), s=len(secs)) + "\n",
    ]
    for code, st in secs.items():
        out.append(f"\n## [{code} · {st[lang]}]({code}/index.md)\n")
        out.append(_recipe_table([i for i in g.items if i.meta["section"] == code], g.path, lang))
    return "\n".join(out) + "\n"


def _recipe_table(items: list[Item], base: Path, lang: str) -> str:
    t = L[lang]
    rows = [f"| {t['id']} | {t['title']} | {t['level']} | {t['status']} |\n|---|---|---|---|"]
    for i in items:
        rows.append(
            f"| [{i.id}]({i.rel(base)}) | {i.title[lang]} | {LEVEL_LABEL[lang][i.meta['level']]} | "
            f"{_status(lang, i.status, i.kind)} |"
        )
    return "\n".join(rows)


def section_page(g: Group, code: str, lang: str) -> str:
    """Section catalog. Also the section's index page in the nav (navigation.indexes)."""
    t = L[lang]
    title = f"{code} · {g.meta['sections'][code][lang]}"
    items = [i for i in g.items if i.meta["section"] == code]
    back = f"{g.code} · {g.meta['title'][lang]}"
    return (
        _front(title)
        + GENERATED
        + f"# {title}\n\n[{back}](../index.md) · "
        + t["section_intro"].format(n=len(items))
        + "\n\n"
        + _recipe_table(items, g.path / code, lang)
        + "\n"
    )


def group_page(g: Group, lang: str) -> str:
    t = L[lang]
    title = f"{g.code} · {g.meta['title'][lang]}"
    out = [
        _front(title),
        GENERATED,
        f"# {title}\n",
        t["group_intro"].format(n=len(g.items)) + "\n",
        f"| {t['id']} | {t['title']} | {t['refs']} | {t['status']} |\n|---|---|---|---|",
    ]
    for i in g.items:
        refs = ", ".join(i.meta.get("recipes", []))
        out.append(
            f"| [{i.id}]({i.rel(g.path)}) | {i.title[lang]} | {refs} | {_status(lang, i.status, i.kind)} |"
        )
    return "\n".join(out) + "\n"


def projects_page(cat: Catalog, lang: str) -> str:
    t = L[lang]
    n = sum(len(g.items) for g in cat.groups.values())
    out = [
        _front(t["projects"]),
        GENERATED,
        f"# {t['projects']}\n",
        t["proj_intro"].format(n=n, g=len(cat.groups)) + "\n",
    ]
    for g in cat.groups.values():
        out.append(f"\n## [{g.code} · {g.meta['title'][lang]}]({g.path.name}/index.md)\n")
        out.append(f"| {t['id']} | {t['title']} | {t['status']} |\n|---|---|---|")
        for i in g.items:
            out.append(
                f"| [{i.id}]({i.rel(PROJECTS)}) | {i.title[lang]} | {_status(lang, i.status, i.kind)} |"
            )
    return "\n".join(out) + "\n"


def _counts(items: list[Item]) -> dict[str, int]:
    c = dict.fromkeys(STATUSES, 0)
    for i in items:
        c[i.status] += 1
    return c


def progress_block(cat: Catalog, lang: str) -> str:
    t = L[lang]
    icons = [STATUS_LABEL[lang][s].split(" ")[0] for s in ("done", "review", "draft", "planned")]
    head = (
        f"| {t['part']} | {t['total']} | " + " | ".join(icons) + f" | {t['progress']} |\n"
        "|---|---|---|---|---|---|---|"
    )
    rows = [head]

    def row(label: str, link: str, items: list[Item]) -> str:
        c = _counts(items)
        pct = round(100 * c["done"] / len(items)) if items else 0
        return (
            f"| [{label}]({link}) | {len(items)} | {c['done']} | {c['review']} | "
            f"{c['draft']} | {c['planned']} | {pct}% |"
        )

    for g in cat.parts.values():
        rows.append(
            row(f"{g.code} · {g.meta['title'][lang]}", f"recipes/{g.path.name}/index.md", g.items)
        )
    for g in cat.groups.values():
        rows.append(
            row(f"{g.code} · {g.meta['title'][lang]}", f"projects/{g.path.name}/index.md", g.items)
        )
    everything = cat.all_items()
    c = _counts(everything)
    rows.append(
        f"| **{t['total']}** | **{len(everything)}** | **{c['done']}** | **{c['review']}** | "
        f"**{c['draft']}** | **{c['planned']}** | "
        f"**{round(100 * c['done'] / len(everything)) if everything else 0}%** |"
    )
    return "\n".join(rows) + "\n"


